"""Merge drivers of scripts/derivations.py, run by a real `git merge` with the repository's
.gitattributes: two agent branches that touch the same declared files merge without a text
conflict, and a frozen hash set differently on both sides still stops the merge."""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

SCOPE = "ee/delivery/FEATURE_SCOPE_REGISTER.csv"
SCOPE_BASE = """unit,kind,public_baseline,scope_class,rule,basis
rust/src/core/a2a,core-module,yes,CORE_KEEP,R11,"coordination"
rust/src/core/cache,core-file,yes,CORE_KEEP,R20,"selection"
rust/src/core/zeta,core-file,no,CORE_KEEP,R20,"selection"
"""
CHANGELOG_BASE = "# Changelog\n\n## [Unreleased]\n\n### Fixed\n\n- older fix\n\n## [3.12.2]\n\n- release\n"
MANIFEST_BASE = 'schema = 1\nnew_paths = [\n  "a.md",\n  "z.md",\n]\n'
HASHES_BASE = '{\n  "a.md": "11",\n  "z.md": "99"\n}\n'
LOCK_HEAD = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n"


def lock(*packages: tuple[str, str, list[str]]) -> str:
    blocks = []
    for name, version, deps in packages:
        block = f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
        if deps:
            block += "dependencies = [\n" + "".join(f' "{d}",\n' for d in deps) + "]\n"
        blocks.append(block)
    return LOCK_HEAD + "".join("\n" + b for b in blocks)


class DerivationMergeTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="derivations-"))
        self.repo = self.tmp / "repo"
        (self.repo / "scripts").mkdir(parents=True)
        shutil.copy(ROOT / "scripts/derivations.py", self.repo / "scripts/derivations.py")
        shutil.copy(ROOT / ".gitattributes", self.repo / ".gitattributes")
        empty = self.tmp / "gitconfig"
        empty.write_text("")
        self.env = {**os.environ, "GIT_CONFIG_GLOBAL": str(empty), "GIT_CONFIG_NOSYSTEM": "1",
                    "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.invalid",
                    "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.invalid"}
        self.git("init", "-q", "-b", "main")
        subprocess.run(["python3", "scripts/derivations.py", "install"], cwd=self.repo, env=self.env,
                       check=True, capture_output=True)
        self.write({SCOPE: SCOPE_BASE, "CHANGELOG.md": CHANGELOG_BASE, "PUBLISH_MANIFEST.toml": MANIFEST_BASE,
                    "docs/contracts/frozen-hashes.json": HASHES_BASE,
                    "rust/Cargo.lock": lock(("app", "0.1.0", ["serde"]), ("serde", "1.0.0", []))})
        self.commit("base")

    def tearDown(self) -> None:
        shutil.rmtree(self.tmp)

    def git(self, *args: str, check: bool = True) -> subprocess.CompletedProcess:
        return subprocess.run(["git", *args], cwd=self.repo, env=self.env, check=check, capture_output=True,
                              text=True)

    def write(self, files: dict[str, str]) -> None:
        for path, text in files.items():
            (self.repo / path).parent.mkdir(parents=True, exist_ok=True)
            (self.repo / path).write_text(text)

    def read(self, path: str) -> str:
        return (self.repo / path).read_text()

    def commit(self, message: str) -> None:
        self.git("add", "-A")
        self.git("commit", "-q", "-m", message)

    def branch(self, name: str, files: dict[str, str]) -> None:
        self.git("checkout", "-q", "-b", name, "main")
        self.write(files)
        self.commit(name)

    def test_two_branches_touching_declared_files_merge_cleanly(self) -> None:
        row_a = 'rust/src/core/bus,core-file,no,CORE_KEEP,R11,"coordination"\n'
        row_b = 'rust/src/core/budget,core-file,no,CORE_KEEP,R11,"coordination"\n'
        scope_lines = SCOPE_BASE.splitlines(keepends=True)
        self.branch("agent-a", {
            SCOPE: "".join(scope_lines[:2] + [row_a] + scope_lines[2:]),
            "CHANGELOG.md": CHANGELOG_BASE.replace("- older fix", "- fix from a\n- older fix"),
            "PUBLISH_MANIFEST.toml": MANIFEST_BASE.replace('  "z.md"', '  "b.md",\n  "z.md"'),
            "docs/contracts/frozen-hashes.json": '{\n  "a.md": "11",\n  "b.md": "22",\n  "z.md": "99"\n}\n',
            "rust/Cargo.lock": lock(("app", "0.1.0", ["log", "serde"]), ("log", "0.4.0", []),
                                    ("serde", "1.0.0", [])),
        })
        self.branch("agent-b", {
            SCOPE: "".join(scope_lines[:2] + [row_b] + scope_lines[2:]),
            "CHANGELOG.md": CHANGELOG_BASE.replace("- older fix", "- fix from b\n- older fix"),
            "PUBLISH_MANIFEST.toml": MANIFEST_BASE.replace('  "z.md"', '  "c.md",\n  "z.md"'),
            "docs/contracts/frozen-hashes.json": '{\n  "a.md": "11",\n  "c.md": "33",\n  "z.md": "99"\n}\n',
            "rust/Cargo.lock": lock(("app", "0.1.0", ["serde", "zstd"]), ("serde", "1.0.0", []),
                                    ("zstd", "0.13.0", [])),
        })
        self.git("checkout", "-q", "agent-a")
        merge = self.git("merge", "--no-edit", "agent-b", check=False)
        self.assertEqual(merge.returncode, 0, merge.stdout + merge.stderr)
        self.assertEqual(self.git("diff", "--name-only", "--diff-filter=U").stdout, "")
        scope = self.read(SCOPE)
        self.assertIn(row_a, scope)
        self.assertIn(row_b, scope)
        self.assertEqual(scope.count("\n"), SCOPE_BASE.count("\n") + 2)
        changelog = self.read("CHANGELOG.md")
        self.assertIn("- fix from a\n", changelog)
        self.assertIn("- fix from b\n", changelog)
        self.assertNotIn("<<<<<<<", changelog)
        manifest = self.read("PUBLISH_MANIFEST.toml")
        self.assertTrue(all(f'  "{p}",\n' in manifest for p in ("a.md", "b.md", "c.md", "z.md")), manifest)
        self.assertEqual(self.read("docs/contracts/frozen-hashes.json"),
                         '{\n  "a.md": "11",\n  "b.md": "22",\n  "c.md": "33",\n  "z.md": "99"\n}\n')
        self.assertEqual(self.read("rust/Cargo.lock"),
                         lock(("app", "0.1.0", ["log", "serde", "zstd"]), ("log", "0.4.0", []),
                              ("serde", "1.0.0", []), ("zstd", "0.13.0", [])))

    def test_frozen_hash_set_differently_on_both_sides_conflicts(self) -> None:
        self.branch("agent-a", {"docs/contracts/frozen-hashes.json": HASHES_BASE.replace('"11"', '"aa"')})
        self.branch("agent-b", {"docs/contracts/frozen-hashes.json": HASHES_BASE.replace('"11"', '"bb"')})
        self.git("checkout", "-q", "agent-a")
        merge = self.git("merge", "--no-edit", "agent-b", check=False)
        self.assertNotEqual(merge.returncode, 0)
        self.assertEqual(self.git("diff", "--name-only", "--diff-filter=U").stdout.split(),
                         ["docs/contracts/frozen-hashes.json"])
        self.assertIn("<<<<<<<", self.read("docs/contracts/frozen-hashes.json"))


if __name__ == "__main__":
    unittest.main()
